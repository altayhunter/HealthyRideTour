def get_coordinates(tour):
	lats = [coordinates[i][0] for i in tour]
	lons = [coordinates[i][1] for i in tour]
	return (lats, lons)

def plot_tours(tours):
	top = -79.908714
	left = 40.422383
	bottom = -80.023727
	right = 40.478815
	m = Basemap(
		llcrnrlon=bottom,
		llcrnrlat=left,
		urcrnrlon=top,
		urcrnrlat=right,
		resolution='i',
		projection='cass',
		lon_0=(top+bottom)/2,
		lat_0=(left+right)/2,
		epsg=4326
	)
	m.arcgisimage(service='World_Street_Map', xpixels=12000, verbose=True)
	for tour in tours:
		tour = tour + [tour[0]]
		(lats, lons) = get_coordinates(tour)
		x, y = m(lons, lats)
		m.plot(x, y, '.-', markersize=10, linewidth=2, color='k', markerfacecolor='b')
	plt.show()

def main():
	for tours in iterations:
		plot_tours(tours)

if __name__ == "__main__":
	main()
